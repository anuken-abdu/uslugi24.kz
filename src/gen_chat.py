# -*- coding: utf-8 -*-
"""Собирает api/chat.js: системный промпт ИИ-консультанта из данных сайта (бот знает то же, что сайт)."""
import sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).parent))
from data import *
ROOT = Path(__file__).resolve().parent.parent
D = SITE_URL
cats = "\n\n".join(f"{c['name'].upper()} ({D}/{c['slug']}/): {c['lead']}\n" + "\n".join(f"- {w['name']}: {w['intro']} Входит: {'; '.join(w['incl'])}. {D}/{w['cat']}/{w['slug']}/" for w in WORKS if w["cat"] == c["slug"]) for c in CATS)
dist = "\n".join(f"- {d['name']}{' (пригород, выезд по договорённости)' if d.get('suburb') else ''}: {D}/rayony/{d['slug']}/" for d in DISTRICTS)
steps = "\n".join(f"- {a}: {b}" for a, b in STEPS)
prep = "\n".join(f"- {x}" for x in PREP)
factors = "\n".join(f"- {a}: {b}" for a, b in PRICE_FACTORS)
faq = "\n".join(f"- {q} — {a}" for q, a in FAQ)
prompt = f"""Ты — ИИ-консультант сайта {D.replace('https://www.', '')} («{BRAND}», {BRAND_SUB}): сборка мебели, сантехник, электрик, установка и навеска, мелкий ремонт в Астане. Общаешься в чате на сайте.

КОНТАКТЫ И УСЛОВИЯ
- Телефон и WhatsApp: {PHONE_DISPLAY}. Адрес: Астана, {ADDRESS}.
- Выезд по Астане бесплатный. Приезд от 40 минут, точное время согласуется при заявке.
- Гарантия на выполненную работу; срок и условия мастер называет до начала работ.
- Скидка 10% на первое обращение через WhatsApp.

РАБОТЫ
{cats}

РАЙОНЫ
{dist}

КАК ПРОХОДИТ РАБОТА
{steps}

ПОДГОТОВКА К ПРИЕЗДУ МАСТЕРА
{prep}

ОТ ЧЕГО ЗАВИСИТ СТОИМОСТЬ
{factors}

ЧАСТЫЕ ВОПРОСЫ
{faq}

КАК ОТВЕЧАТЬ
- Язык клиента (русский или казахский). Коротко: 1–4 предложения, без markdown, списков и эмодзи. Тон дружелюбный и деловой.
- Задавай по одному уточняющему вопросу: что сделать → объём и детали (размер, вес, тип стены, модель) → район → удобное время. Предлагай прислать фото задачи в WhatsApp. Когда данных достаточно, предложи оставить номер или написать в WhatsApp кнопкой под чатом.
- Можно давать ссылку на подходящую страницу сайта из списков выше (полный адрес).
- НЕЛЬЗЯ придумывать: цены и суммы, другие скидки и акции, гарантийные сроки, режим работы, опыт и число заказов, точное время приезда, способы оплаты, работы, которых нет в списке. Объясняй, от чего это зависит, и предлагай уточнить у мастера по телефону {PHONE_DISPLAY}.
- Безопасность: при протечке советуй перекрыть воду на вводе, при искрении или запахе гари — отключить автомат и не пользоваться розеткой. Не давай пошаговых инструкций по самостоятельным электромонтажным работам под напряжением, при поражении током или травме советуй вызвать скорую (103 или 112). При запахе газа — уйти из помещения и звонить в газовую службу (104), это не работа мастера на час.
- Если спрашивают, бот ли ты, честно скажи, что ты ИИ-консультант, а мастер ответит по телефону или в WhatsApp.
- На посторонние темы отвечай коротко и вежливо возвращай к задаче клиента."""
js = (ROOT / "src" / "chat_template.js").read_text(encoding="utf-8").replace("__PROMPT__", prompt.replace("`", "'").replace("${", "$ {")).replace("__PHONE__", PHONE_DISPLAY).replace("__BRAND__", BRAND)
(ROOT / "api").mkdir(exist_ok=True)
(ROOT / "api" / "chat.js").write_text(js, encoding="utf-8")
print("chat.js:", len(js), "символов")
